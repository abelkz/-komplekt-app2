/// Склейка строк прайса с карточками общего каталога.
///
/// Почему это отдельный файл. Смысл приложения — сравнение цен, а оно
/// работает только если один и тот же товар у двух поставщиков стал ОДНОЙ
/// карточкой с двумя предложениями (модель заведена миграцией 0013:
/// `products` — карточка, `offers` — цена конкретного продавца). Ключ
/// склейки — заводской артикул, и пишут его все по-разному:
/// «DD-640200 R», «dd640200r», «DD640200R» — это один керамогранит.
///
/// До нормализации импорт сравнивал строки буква в букву: не находил
/// существующую карточку, пытался создать дубль и упирался в уникальный
/// индекс `products_brand_sku_uniq` (он построен по `upper(sku)`) — падал
/// весь прайс целиком с непонятной поставщику ошибкой.
library;

/// Всё, кроме букв (латиница и кириллица) и цифр. Дефисы, пробелы, точки,
/// слэши и подчёркивания в артикуле каждый ставит как ему удобно, так что
/// для сравнения это мусор.
final RegExp _junk = RegExp(r'[^0-9A-ZА-ЯЁ]');

/// Несколько пробелов подряд, табы и переводы строк.
final RegExp _spaces = RegExp(r'\s+');

/// Нормализованный артикул — ключ склейки карточек.
///
/// Возвращает null, если после очистки ничего не осталось: такой товар
/// склеивать не с чем, он заведёт свою карточку.
String? normSku(String? raw) {
  if (raw == null) return null;
  final cleaned = raw.toUpperCase().replaceAll(_junk, '');
  return cleaned.isEmpty ? null : cleaned;
}

/// Нормализованное название — им склеиваем строки внутри одного файла,
/// когда артикула нет вовсе (цемент, песок, штукатурка — у них заводского
/// артикула не бывает).
///
/// Для склейки с ЧУЖИМИ карточками этого мало: разные товары легко носят
/// похожие имена, и ошибочное слияние дороже лишнего дубля. Поиск похожих
/// названий по всему каталогу — отдельная задача (триграммы на стороне
/// базы, с подтверждением человеком).
String normName(String raw) =>
    raw.trim().toUpperCase().replaceAll(_spaces, ' ');

/// Написания артикула, которые стоит поискать в базе.
///
/// PostgREST сравнивает `in` регистрозависимо, а нормализованной колонки
/// в базе пока нет, поэтому спрашиваем сразу несколько написаний одним
/// запросом: как в прайсе, ВЕРХНИМ регистром, нижним и без разделителей.
/// Это покрывает почти все реальные случаи; остальное добирает запасной
/// путь импорта — он ловит отказ уникального индекса и добавляет цену
/// к уже существующей карточке вместо того, чтобы упасть.
List<String> skuLookupVariants(String? raw) {
  final s = raw?.trim();
  if (s == null || s.isEmpty) return const [];
  final norm = normSku(s);
  return <String>{
    s,
    s.toUpperCase(),
    s.toLowerCase(),
    if (norm != null) norm,
    if (norm != null) norm.toLowerCase(),
  }.toList();
}

/// Делит список на пачки по [size] — чтобы длинный прайс не уехал в базу
/// одним запросом на сто тысяч символов и чтобы одна плохая пачка не
/// утащила за собой весь файл.
Iterable<List<T>> chunked<T>(List<T> list, int size) {
  assert(size > 0);
  return Iterable<List<T>>.generate(
    (list.length + size - 1) ~/ size,
    (i) => list.sublist(
      i * size,
      (i * size + size) > list.length ? list.length : i * size + size,
    ),
  );
}

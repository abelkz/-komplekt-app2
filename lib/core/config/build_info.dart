/// Метка сборки — короткий номер коммита, из которого собрано приложение.
///
/// Подставляется при сборке (`--dart-define=BUILD_TAG=...` в GitHub Actions)
/// и показывается внизу экрана «Профиль». Нужна, чтобы отличать свежую
/// версию от закэшированной старой: браузер и домашний экран iOS держат
/// прошлую сборку неделями, и по внешнему виду это не понять.
class BuildInfo {
  BuildInfo._();

  static const tag = String.fromEnvironment('BUILD_TAG', defaultValue: 'local');

  /// Строка для подписи внизу профиля.
  static String get label => 'КОМПЛЕКТ · сборка $tag';

  /// Адрес, по которому приложение открывается в браузере.
  ///
  /// Сюда ведут ссылки, которыми делятся из карточки товара: у прораба на
  /// том конце может не стоять приложение, и страница должна открыться
  /// просто по нажатию. Веб-сборка ходит в ту же живую базу, а каталог
  /// открыт гостю — поэтому получателю не нужен ни аккаунт, ни установка.
  ///
  /// `#` в адресе не опечатка: url-стратегия по умолчанию хеш-based
  /// (usePathUrlStrategy в проекте не включён), и без решётки GitHub Pages
  /// отдаст 404 вместо приложения.
  ///
  /// Меняется в одном месте — когда появится свой домен, правится здесь.
  static const webBase = String.fromEnvironment(
    'WEB_BASE',
    defaultValue: 'https://abelkz.github.io/-komplekt-app2/#',
  );

  /// Ссылка на карточку товара для пересылки.
  static String productLink(String id) => '$webBase/product/$id';
}

-- ============================================================
-- КОМПЛЕКТ · 0045 — ссылка на товар у продавца
--
-- Зачем. У предложения была только ссылка на сайт магазина
-- (suppliers.website), и покупатель с карточки «Керамогранит Estima
-- Bolero 60×60» попадал на главную страницу, где этот товар надо
-- искать заново. Это теряет человека ровно в тот момент, когда он
-- уже выбрал и готов покупать, — и обесценивает переход для самого
-- магазина, который нас и позвал ради заявок.
--
-- Колонка у ПРЕДЛОЖЕНИЯ, а не у карточки: карточка общая для всех
-- продавцов, а ссылка у каждого своя.
--
-- Заполняется при заливке каталога и поддерживается синхронизацией
-- цен (tools/price_sync.py). Пусто — приложение показывает кнопку
-- «Сайт» со ссылкой на магазин, как раньше.
-- ============================================================

alter table public.offers
  add column if not exists product_url text;

comment on column public.offers.product_url is
  'Страница этого товара у продавца. Пусто — ведём на сайт магазина';

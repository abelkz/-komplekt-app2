-- ============================================================================
-- 0049 — номер товара на Kaspi переезжает из attrs в свою колонку
-- ============================================================================
--
-- ЗАЧЕМ. `products.attrs` — это характеристики товара, которые приложение
-- показывает покупателю как есть: «фактура: матовая», «класс: 33». Номер
-- товара на площадке лежал там же, потому что отдельное место под него
-- потребовало бы миграции, — и уехал на экран: в карточке над ценами
-- красовалась плашка «KASPI_ID: 113711231». Заметно на первом же
-- скриншоте, который владелец приложения прислал, сравнивая цены с Kaspi.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ФИЛЬТР В ПРИЛОЖЕНИИ. Фильтр в коде приедет только
-- с новой сборкой, а плашку видят уже сейчас — в версии из стора. Убрать
-- служебное поле из данных — единственный способ починить и её тоже.
--
-- Синхронизация (tools/price_sync.py) читает номер из новой колонки.
--
-- Идемпотентна: повторный запуск ничего не меняет.
-- ============================================================================

alter table public.products add column if not exists kaspi_id text;

comment on column public.products.kaspi_id is
  'Номер товара на Kaspi.kz. Служебное: по нему синхронизация цен находит '
  'продавцов. Покупателю не показывается — поэтому не в attrs.';

update public.products
   set kaspi_id = attrs->>'kaspi_id',
       attrs    = attrs - 'kaspi_id'
 where attrs ? 'kaspi_id';

-- Синхронизация выбирает карточки площадки именно по этому полю.
create index if not exists products_kaspi_id_idx
  on public.products (kaspi_id) where kaspi_id is not null;

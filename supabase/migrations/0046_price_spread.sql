-- ============================================================================
-- 0046. «Где цены расходятся» — товары с настоящим разбросом цен.
--
-- ЗАЧЕМ. Секция на главной называется «Где цены расходятся» и помечена
-- «ВЫГОДА», но набиралась она из первой страницы ленты: брались 20 самых
-- новых карточек, сортировались по разбросу и показывались первые 10.
-- Проверки «разброс вообще есть» там не было. А самые новые карточки —
-- это свежезалитый магазин, у каждой по одному продавцу, то есть разброс
-- ровно ноль. Секция показывала десять карточек с одной ценой и обещала
-- выгоду, которой нет.
--
-- Хуже того, 228 карточек, где разброс настоящий (до +126%), в первую
-- страницу ленты не попадают: их created_at намеренно сдвинут назад,
-- чтобы они не заняли ленту целиком (см. CLAUDE.md, объявления Kaspi).
-- То есть единственная секция ради сравнения цен была выключена ровно
-- тем, что должно было её наполнить.
--
-- ПОЧЕМУ ФУНКЦИЯ. Считать надо по всему каталогу, а не по тому, что
-- приложение успело загрузить: разброс — свойство карточки, а не страницы
-- ленты. Тянуть все предложения на клиент ради этого бессмысленно, тем
-- более что PostgREST отдаёт максимум 1000 строк (CLAUDE.md, предел
-- кусал трижды).
--
-- В отличие от price_drops (0027), здесь НЕ нужен security definer:
-- offers открыты на чтение всем (политики каталога — using (true)),
-- закрытой price_history функция не касается. Меньше прав — меньше
-- способов ошибиться.
--
-- СЧИТАЕМ ПО ВСЕМ ПРЕДЛОЖЕНИЯМ, включая «нет в наличии». Это сознательно:
-- ровно так же считает Product.savingPercent на клиенте, и если считать
-- здесь иначе, процент в секции разойдётся с процентом на самой карточке.
-- Расхождение в цифрах между двумя экранами подрывает доверие сильнее,
-- чем чуть завышенная выгода.
--
-- Типы (bigint) — как в живой базе, ключи там целочисленные (CLAUDE.md §6.1).
-- Скрипт идемпотентный: повторный запуск безопасен.
-- ============================================================================

create or replace function public.price_spread(
  p_limit int default 20
)
returns table (
  product_id   bigint,
  min_price    numeric,
  max_price    numeric,
  offers_count int,
  pct          int
)
language sql
stable
set search_path = public
as $$
  with per_product as (
    select o.product_id,
           min(o.price)  as mn,
           max(o.price)  as mx,
           count(*)::int as cnt
      from public.offers o
     where o.price > 0
     group by o.product_id
  )
  select product_id,
         mn,
         mx,
         cnt,
         round((1 - mn / mx) * 100)::int
    from per_product
   where cnt >= 2
     and mx > 0
     and mn < mx
     -- Округление до процента: «+0,4 %» — это шум, а не повод
     -- открыть товар. Та же отсечка, что у price_drops.
     and round((1 - mn / mx) * 100) >= 1
   order by round((1 - mn / mx) * 100) desc, product_id
   limit greatest(p_limit, 1);
$$;

revoke all on function public.price_spread(int) from public;
grant execute on function public.price_spread(int) to anon, authenticated;

comment on function public.price_spread(int) is
  'Товары, у которых несколько продавцов и цены расходятся. Отдаёт разрыв '
  'между самой дешёвой и самой дорогой ценой. Считает по всему каталогу, '
  'а не по загруженной странице ленты';

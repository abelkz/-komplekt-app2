-- КОМПЛЕКТ · 0036 — починка счётчика идентификаторов у brands
--
-- Что было. В живой базе шесть марок приехали из начального наполнения
-- с явно проставленными id (1..6), а последовательность так и осталась
-- на единице: через nextval в brands никто никогда не вставлял. До
-- миграции 0034 это было незаметно — приложение марки только читало.
--
-- Как проявлялось. Первая же попытка завести новую марку из формы товара
-- (set_product_brand) падала с
--     23505: duplicate key value violates unique constraint "brands_pkey"
--     DETAIL: Key (id)=(1) already exists.
-- То есть подстановка уже существующей марки работала, а создание новой —
-- нет. Поймано 19.09.2026 при проверке функций админки.
--
-- Проверено тогда же: у products (68/68), offers (50/50) и suppliers
-- (21/21) счётчики в порядке — эти таблицы приложение наполняет само,
-- и последовательность у них шла нормально. Сломана была только brands.
--
-- Разворачиванию с нуля миграция не мешает: на пустой таблице
-- max(id) = 0, и setval вернёт последовательность к исходному состоянию.
-- ============================================================

select setval(
  pg_get_serial_sequence('public.brands', 'id'),
  -- greatest, чтобы случайный повторный прогон не сдвинул счётчик назад
  greatest(
    (select coalesce(max(id), 0) from public.brands),
    (select coalesce(last_value, 1) from pg_sequences
      where schemaname = 'public'
        and sequencename =
            split_part(pg_get_serial_sequence('public.brands', 'id'), '.', 2))
  ),
  -- true: следующий nextval выдаст значение на единицу больше
  true
);

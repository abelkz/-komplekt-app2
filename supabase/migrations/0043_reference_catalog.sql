select r.name, r.unit, r.category_slug, 'admin',
       -- Владельцем ставим администратора: в живой базе owner_id может
       -- быть обязательным, а карточка справочника всё равно его.
       (select p.id from public.profiles p
         where p.role = 'admin' order by p.id limit 1)
  from ref r
 where not exists (
   select 1 from public.products p
    where p.name_norm = public.norm_name(r.name)
      and coalesce(p.category_slug, '') = r.category_slug
 );


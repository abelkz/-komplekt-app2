-- КОМПЛЕКТ · 0043 — справочник товаров (карточки без цен)
--
-- Зачем. В каталоге было 30 карточек: поставщику нечего показать, а
-- покупателю нечего искать. Справочник закрывает курицу и яйцо с
-- другой стороны — товар в каталоге уже есть, поставщику остаётся
-- поставить свою цену, а не заводить карточку с нуля.
--
-- Откуда данные. Названия товаров, которые реально продаются в
-- Астане (megastroy.kz, 534 позиций по восьми категориям).
-- Взяты ТОЛЬКО факты о товаре: название, как его пишет рынок, и
-- единица измерения. Ни цен, ни фотографий, ни описаний, ни названий
-- магазинов — фото и тексты чужие, а цена, снятая один раз, назавтра
-- уже неверна и подрывает доверие сильнее, чем её отсутствие.
--
-- Почему имя целиком, как на рынке. Склейка по названию
-- (match_products_by_name, миграция 0040) требует ТОЧНОГО совпадения
-- после нормализации. Поставщик пишет в прайсе ровно так же —
-- «Краска Dulux Professional Diamond Max Protect мат BW 1л», — и его
-- строка ляжет на готовую карточку, а не создаст дубль.
--
-- Артикулы не проставлены намеренно. В названиях они местами видны
-- (у обоев 60637-03, у ламината 62365), но вытащить их разбором без
-- ошибок нельзя, а неверный артикул склеит два РАЗНЫХ товара в один —
-- это хуже лишней карточки и автоматически не чинится.
--
-- source = 'admin' помечает карточку справочника: импорт поставщика
-- такие не перетирает.
--
-- Карточки без предложений не попадают в ленту на главной и уходят
-- в конец списка в категориях — иначе первым экраном приложения стал
-- бы список «цена не указана».
--
-- Применять ПОСЛЕ 0040 (нужны name_norm и source).

-- ============================================================================
-- 0012. Администратор тоже может вести каталог.
--
-- ПРОБЛЕМА:
--   Все правила записи в products и offers опираются на функцию
--   is_approved_supplier(). Она проверяет роль 'supplier' — и владелец
--   проекта с ролью 'admin' под неё не подпадает: товар не создаётся,
--   цена не сохраняется, хотя прав у него по смыслу больше всех.
--
--   Симптом в базе: товар «Розетки» создан, а строки цены к нему нет —
--   вставка в offers была отклонена.
--
-- РЕШЕНИЕ:
--   Переписываем функцию: одобренный поставщик ИЛИ администратор.
--   Сами правила не трогаем — они все вызывают эту функцию, так что
--   достаточно поправить её одну.
--
-- Применять: Supabase → SQL Editor → вставить целиком → Run.
-- Скрипт идемпотентный: повторный запуск безопасен.
-- ============================================================================

create or replace function public.is_approved_supplier()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
      from public.profiles p
     where p.id = auth.uid()
       and (
         -- обычный поставщик: роль supplier и заявка одобрена
         (p.role = 'supplier' and p.status = 'approved')
         -- администратор ведёт каталог без отдельной заявки
         or p.role = 'admin'
       )
  );
$$;

